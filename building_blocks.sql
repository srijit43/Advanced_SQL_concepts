SELECT 
    e.EmployeeName,
    e.Salary,
    d.DepartmentName
FROM 
    Employees_sq e
JOIN 
    Departments_sq d
ON 
    e.DepartmentID = d.DepartmentID
WHERE 
    e.Salary > (
        SELECT 
            AVG(Salary)
        FROM 
            Employees_sq
        WHERE 
            DepartmentID = e.DepartmentID
    );


