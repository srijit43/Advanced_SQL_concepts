With Cte as
(
Select p.productID, p.productName,
p.price ,
s.quantity
from Products_q1 as p
left join
Sales_q1 as s
on 
p.ProductID = s.ProductID

)

Select 
productID, productName,
sum(price * quantity) as total_revenue
from cte
group by productID, productName
order by sum(price * quantity) desc;



